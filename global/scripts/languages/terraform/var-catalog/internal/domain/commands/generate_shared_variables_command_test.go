package commands_test

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/rios0rios0/pipelines/global/scripts/languages/terraform/var-catalog/internal/domain/commands"
	"github.com/rios0rios0/pipelines/global/scripts/languages/terraform/var-catalog/internal/test/doubles"
)

const catalog = "environment = <<-EOT\n  variable \"environment\" {}\nEOT\n"

const generated = "# AUTOGENERATED by var-catalog from .terraform-var-catalog.hcl -- do not edit.\n" +
	"# Regenerate with the var-catalog runner (a consumer may wrap it in a make target).\n\n" +
	"variable \"environment\" {}\n"

func TestGenerateSharedVariablesCommand(t *testing.T) {
	t.Parallel()

	t.Run("should write a missing file and remove a stale one when writing", func(t *testing.T) {
		t.Parallel()
		// given
		repository := doubles.NewInMemoryStacksRepository(catalog, map[string][]string{
			"stacks/a": {"x = var.environment\n"},
			"stacks/b": {"x = 1\n"},
		})
		repository.Files["stacks/b"] = "# stale\n"

		// when
		result, err := commands.NewGenerateSharedVariablesCommand(repository).Execute(commands.ModeWrite)

		// then
		require.NoError(t, err)
		assert.Equal(t, []string{"stacks/a/variables-shared.tf", "stacks/b/variables-shared.tf"}, result.Drift)
		assert.Equal(t, 2, result.Written)
		assert.Equal(t, generated, repository.Files["stacks/a"])
		assert.Equal(t, []string{"stacks/b"}, repository.Removals)
	})

	t.Run("should report drift and write nothing when checking", func(t *testing.T) {
		t.Parallel()
		// given
		repository := doubles.NewInMemoryStacksRepository(catalog, map[string][]string{
			"stacks/a": {"x = var.environment\n"},
		})

		// when
		result, err := commands.NewGenerateSharedVariablesCommand(repository).Execute(commands.ModeCheck)

		// then
		require.NoError(t, err)
		assert.Equal(t, []string{"stacks/a/variables-shared.tf"}, result.Drift)
		assert.Zero(t, result.Written)
		assert.Empty(t, repository.Writes)
	})

	t.Run("should leave an up-to-date file and preserve a hand-written declaration", func(t *testing.T) {
		t.Parallel()
		// given
		repository := doubles.NewInMemoryStacksRepository(catalog, map[string][]string{
			"stacks/a": {"x = var.environment\n"},
			"stacks/b": {"x = var.environment\nvariable \"environment\" {}\n"},
		})
		repository.Files["stacks/a"] = generated

		// when
		result, err := commands.NewGenerateSharedVariablesCommand(repository).Execute(commands.ModeWrite)

		// then
		require.NoError(t, err)
		assert.Empty(t, result.Drift)
		assert.Equal(t, []string{"stacks/b: environment"}, result.Preserved)
		assert.Empty(t, repository.Writes)
	})

	t.Run("should say there is nothing to do when the catalog has no entry", func(t *testing.T) {
		t.Parallel()
		// given
		repository := doubles.NewInMemoryStacksRepository("locals {}\n", map[string][]string{"stacks/a": {"var.x"}})

		// when
		result, err := commands.NewGenerateSharedVariablesCommand(repository).Execute(commands.ModeWrite)

		// then
		require.NoError(t, err)
		assert.True(t, result.NoCatalog)
	})

	t.Run("should stop at a stack it cannot read", func(t *testing.T) {
		t.Parallel()
		// given
		repository := doubles.NewInMemoryStacksRepository(catalog, map[string][]string{"stacks/a": {"var.environment"}})
		repository.Unreadable = "stacks/a"

		// when
		_, err := commands.NewGenerateSharedVariablesCommand(repository).Execute(commands.ModeWrite)

		// then
		require.ErrorIs(t, err, doubles.ErrUnreadable)
	})
}
