package entities

import (
	"slices"
	"strconv"
	"strings"

	"github.com/rios0rios0/pipelines/global/scripts/languages/terraform/internal/text"
)

// headerComment opens every report, saying what it measures and what it
// cannot, so nobody reads more precision into it than it has.
const headerComment = `<!--
  Generated by global/scripts/languages/terraform/terra-test/coverage
  in SonarQube's generic coverage format.

  One lineToCover per top level BLOCK (resource, data, module, output, check),
  placed on the block's declaration line. covered="true" means the block is
  reachable from an assertion ` + "`terraform test`" + ` actually executes: an assert
  condition or an expect_failures entry in tests/*.tftest.hcl, the module's
  own check blocks, or a lifecycle precondition/postcondition, followed through
  local, output and variable validation expressions.

  CAVEAT, BLOCK GRANULARITY: the unit of measurement is the block, not the
  line. A 220 line resource counts as covered off a single attribute
  assertion, so this report says which blocks are exercised at all, never how
  much of each block is exercised. Stated here on purpose instead of being
  hidden behind a line count that would look more precise than it is.
-->`

// Coverage is, per file relative to the repository, whether each declaration
// line is covered. Two blocks declared on one line collapse to one entry, and
// covered wins: the line IS exercised.
type Coverage map[string]map[int]bool

// Mark records one declared block.
func (c Coverage) Mark(path string, line int, covered bool) {
	if c[path] == nil {
		c[path] = map[int]bool{}
	}
	c[path][line] = c[path][line] || covered
}

// Render is the report in SonarQube's generic coverage format, files in path
// order and lines ascending; an empty but valid document when nothing was
// measured.
func Render(coverage Coverage) string {
	lines := []string{`<?xml version="1.0" encoding="UTF-8"?>`, headerComment}
	if len(coverage) == 0 {
		lines = append(lines, `<coverage version="1"/>`)
		return strings.Join(lines, "\n") + "\n"
	}
	lines = append(lines, `<coverage version="1">`)
	files := make([]string, 0, len(coverage))
	for path := range coverage {
		files = append(files, path)
	}
	slices.Sort(files)
	for _, path := range files {
		lines = append(lines, `  <file path="`+text.EscapeXML(path)+`">`)
		numbers := make([]int, 0, len(coverage[path]))
		for number := range coverage[path] {
			numbers = append(numbers, number)
		}
		slices.Sort(numbers)
		for _, number := range numbers {
			lines = append(lines, `    <lineToCover lineNumber="`+strconv.Itoa(number)+
				`" covered="`+strconv.FormatBool(coverage[path][number])+`"/>`)
		}
		lines = append(lines, "  </file>")
	}
	lines = append(lines, "</coverage>")
	return strings.Join(lines, "\n") + "\n"
}
